AR = '؀-ۿ'


def word_sub(text, a, b):
    # A word may carry a leading "و" (and), as in "قارن واختر".
    return re.sub(r'(?<![%s])(و?)%s(?![%s])' % (AR, re.escape(a), AR), lambda m: m.group(1) + b, text)


def transform(lit, fname):
    if fname == 'lights.dart' and lit in ('العريس', 'العروسة'):
        return lit  # the whose-plan cards keep both choices
    if fname == 'sections.dart' and lit == 'العروسة':
        return 'العريس'  # her partner's role in her participants list
    if lit in EXACT:
        return EXACT[lit]
    out = lit
    for a, b in WORDS:
        out = word_sub(out, a, b)
    return out


LIT = re.compile(r"'((?:[^'\\\n]|\\.)*)'")


def convert(src, fname, log):
    def rep(m):
        lit = m.group(1)
        if not re.search('[%s]' % AR, lit):
            return m.group(0)
        new = transform(lit, fname)
        if new != lit:
            log.append((fname, lit, new))
        return "'" + new.replace("'", "\\'") + "'"
    lines = src.split('\n')
    for i, line in enumerate(lines):
        if line.lstrip().startswith(('import ', '//', 'export ')):
            continue
        lines[i] = LIT.sub(rep, line)
    return '\n'.join(lines)


def main():
    if os.path.exists(OUT):
        shutil.rmtree(OUT)
    log = []
    for d in ('c_journey', 'v3'):
        os.makedirs(os.path.join(OUT, d))
        for f in sorted(os.listdir(os.path.join(ROOT, d))):
            if not f.endswith('.dart') or (d == 'c_journey' and f.endswith('_test.dart')):
                continue
            src = open(os.path.join(ROOT, d, f)).read()
            if f == 'v3_test.dart':
                src = src.replace("'../../support/preview_fonts.dart'", "'../../../../support/preview_fonts.dart'")
                # Splash, welcome and whose-plan come before the choice, so
                # they stay neutral; the bride's page reuses the groom's.
                src = re.sub(r"\s*\('a0(1_splash|2_who|2b_whose|2c_whose_bride)'.*?, 844\),", '', src)
                # The participant is a journey of its own, not the owner's.
                src = re.sub(r"\s*\('(q\d\d_|w16_)[a-z_]+', [^)]*\),", '', src)
            if d == 'v3':
                for a, b in BRIDE_SRC.get(f, []):
                    assert src.count(a) >= 1, (f, a)
                    src = src.replace(a, b)
            if d == 'v3' and f == 'home.dart':
                # Her wedding-day afternoon is getting ready, not the men's maqyal.
                src = src.replace("'المقيل',\n              'الديوان · القات عند أخوك صالح'",
                                  "'التجهيز',\n              'البيت · الكوافيرة مع أختك نورة'")
            if d == 'v3':
                src = src.replace('LucideIcons.music', 'LucideIcons.sparkles').replace('LucideIcons.leaf', 'LucideIcons.flame')
            open(os.path.join(OUT, d, f), 'w').write(convert(src, f, log))
    with open(os.path.join(ROOT, 'bride_profile', 'changes.tsv'), 'w') as fh:
        seen = set()
        for f, a, b in log:
            if (a, b) in seen:
                continue
            seen.add((a, b))
            fh.write('%s\t%s\t%s\n' % (f, a, b))
    print('changed literals:', len(log), 'unique:', len(seen))


if __name__ == '__main__':
    sys.exit(main())
